export function cityStatusOf(city: string): CityStatus | "unknown" | null {
  const value = city.trim().toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");
  if (!value) return null;
  return cityStatuses.find((item) => item.city.toLowerCase().replace(/ё/g, "е") === value)?.status ?? "unknown";
}
